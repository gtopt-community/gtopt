"""Write a gtopt planning (and optionally its solved dispatch) as OpenDSS.

The script is a balanced three-phase model of gtopt's single-phase
equivalent, so OpenDSS can run an AC power flow of exactly the network
gtopt optimised and report voltages, losses and flows:

* the slack bus (``reference_voltage`` or ``reference_theta``) is the
  circuit's ``Vsource`` (``pu`` = reference voltage, near-zero
  impedance);
* a Line with equal bus voltages and no tap becomes an OpenDSS ``Line``
  (``r1 = r0`` and ``x1 = x0`` in ohm, ``length=1 units=none``, no
  charging); a transformer (``type = transformer``, a ``tap_ratio`` or
  different bus kV) becomes a two-winding wye-wye ``Transformer`` whose
  per-unit impedance reproduces the line's ohms at ``bus_b``, with
  ``taps = [1, 1/tap_ratio]``;
* Demand -> ``Load`` (model 1, constant PQ, wide ``vminpu``/``vmaxpu``
  so OpenDSS never switches the model); Generator -> ``Generator``
  (model 1, fixed kW/kvar); Battery net injection -> ``Generator``
  (discharge) or ``Load`` (charge); Bus ``shunt_q`` ->
  ``Capacitor`` (kvar at the bus base voltage).

Without a results directory loads take ``lmax`` and generators ``pmax``
at the chosen block (reactive from ``power_factor``); with one, the
solved ``load``/``generation``/``qgen``/``tap`` values are
used.  ``Set ControlMode=OFF`` keeps OpenDSS from moving taps or
capacitors, so the AC solution is the AC image of gtopt's decisions.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

SQRT3 = math.sqrt(3.0)


@dataclass
class Dispatch:
    """Per-element values of one block (MW / MVAr / pu)."""

    load: dict[str, float] = field(default_factory=dict)
    qload: dict[str, float] = field(default_factory=dict)
    gen: dict[str, float] = field(default_factory=dict)
    qgen: dict[str, float] = field(default_factory=dict)
    battery: dict[str, float] = field(default_factory=dict)  # net discharge
    tap: dict[str, float] = field(default_factory=dict)
    line_capacity: dict[str, float] = field(default_factory=dict)


def _sched(value: Any, block: int) -> float | None:
    """Scalar of a gtopt field schedule at the flat block index."""
    if value is None or isinstance(value, str):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    flat: list[float] = []

    def walk(v: Any) -> None:
        if isinstance(v, list):
            for x in v:
                walk(x)
        else:
            flat.append(float(v))

    walk(value)
    if not flat:
        return None
    return flat[min(block, len(flat) - 1)]


def tan_phi(pf: float | None) -> float:
    """``Q/P`` of a signed power factor (negative = leading)."""
    if pf is None or pf == 0 or abs(pf) >= 1.0:
        return 0.0
    return math.copysign(math.sqrt(1.0 / (pf * pf) - 1.0), pf)


def _dss_name(name: Any) -> str:
    s = str(name)
    return "".join(c if c.isalnum() or c in "_-" else "_" for c in s)


def _bus_key(ref: Any, by_uid: dict[int, str]) -> str:
    if isinstance(ref, int):
        return by_uid[ref]
    return str(ref)


def planning_to_dss(
    planning: dict[str, Any],
    *,
    block: int = 0,
    dispatch: Dispatch | None = None,
    frequency: float = 60.0,
) -> str:
    """Render *planning* (at flat block index *block*) as a .dss script."""
    system = planning["system"]
    buses = system.get("bus_array", [])
    by_uid = {int(b["uid"]): str(b["name"]) for b in buses}
    kv = {str(b["name"]): float(b.get("voltage", 1.0) or 1.0) for b in buses}
    slack = next(
        (b for b in buses if b.get("reference_voltage") is not None),
        next((b for b in buses if b.get("reference_theta") is not None), buses[0]),
    )
    vref = float(slack.get("reference_voltage", 1.0))
    slack_name = str(slack["name"])
    d = dispatch or Dispatch()

    out: list[str] = [
        "! Generated by gtopt2opendss -- balanced 3-phase image of a gtopt case",
        "Clear",
        f"Set DefaultBaseFrequency={frequency:g}",
        f"New Circuit.{_dss_name(system.get('name', 'gtopt'))} "
        f"basekv={kv[slack_name]:.9g} pu={vref:.9g} phases=3 "
        f"bus1={_dss_name(slack_name)} R1=0 X1=1e-9 R0=0 X0=1e-9",
        "",
    ]
    for line in system.get("line_array", []):
        if _unbuilt(line, d):
            continue  # expansion candidate the solution did not build
        a = _bus_key(line["bus_a"], by_uid)
        b = _bus_key(line["bus_b"], by_uid)
        out.append(_branch(line, a, b, kv, block, d))
    out.append("")

    for dem in system.get("demand_array", []):
        name = str(dem["name"])
        bus = _bus_key(dem["bus"], by_uid)
        p = d.load.get(name)
        if p is None:
            p = _sched(dem.get("lmax"), block) or 0.0
        q = d.qload.get(name, p * tan_phi(dem.get("power_factor")))
        out.append(
            f"New Load.{_dss_name(name)} bus1={_dss_name(bus)} phases=3 conn=wye "
            f"kV={kv[bus]:.9g} kW={p * 1000:.9g} kvar={q * 1000:.9g} model=1 "
            "vminpu=0.5 vmaxpu=1.5"
        )
    for gen in system.get("generator_array", []):
        name = str(gen["name"])
        bus = _bus_key(gen["bus"], by_uid)
        if bus == slack_name:
            continue  # the Vsource is the slack injection
        p = d.gen.get(name)
        if p is None:
            p = _sched(gen.get("pmax"), block) or 0.0
        q = d.qgen.get(name, p * tan_phi(gen.get("power_factor")))
        out.append(
            f"New Generator.{_dss_name(name)} bus1={_dss_name(bus)} phases=3 "
            f"kV={kv[bus]:.9g} kW={p * 1000:.9g} kvar={q * 1000:.9g} model=1 "
            "vminpu=0.5 vmaxpu=1.5"
        )
    for bat in system.get("battery_array", []):
        name = str(bat["name"])
        bus = _bus_key(bat["bus"], by_uid)
        net = d.battery.get(name, 0.0)
        if net >= 0:
            out.append(
                f"New Generator.bat_{_dss_name(name)} bus1={_dss_name(bus)} "
                f"phases=3 kV={kv[bus]:.9g} kW={net * 1000:.9g} kvar=0 model=1 "
                "vminpu=0.5 vmaxpu=1.5"
            )
        else:
            out.append(
                f"New Load.bat_{_dss_name(name)} bus1={_dss_name(bus)} phases=3 "
                f"kV={kv[bus]:.9g} kW={-net * 1000:.9g} kvar=0 model=1 "
                "vminpu=0.5 vmaxpu=1.5"
            )
    for bus in buses:
        q = bus.get("shunt_q")
        if q:
            bname = str(bus["name"])
            out.append(
                f"New Capacitor.shunt_{_dss_name(bname)} bus1={_dss_name(bname)} "
                f"phases=3 kV={kv[bname]:.9g} kvar={float(q) * 1000:.9g}"
            )
    bases = sorted(set(kv.values()))
    out += [
        "",
        "Set VoltageBases=[" + " ".join(f"{v:.9g}" for v in bases) + "]",
        "CalcVoltageBases",
        "Set ControlMode=OFF",
        "Set MaxIterations=100",
        "Solve",
        "",
    ]
    return "\n".join(out)


def _branch(
    line: dict[str, Any],
    a: str,
    b: str,
    kv: dict[str, float],
    block: int,
    d: Dispatch,
) -> str:
    name = _dss_name(line["name"])
    r = float(_sched(line.get("resistance"), block) or 0.0)
    x = float(_sched(line.get("reactance"), block) or 0.0)
    tap = d.tap.get(str(line["name"]))
    if tap is None:
        tap = float(_sched(line.get("tap_ratio"), block) or 1.0)
    is_xf = (
        line.get("type") == "transformer"
        or abs(tap - 1.0) > 1e-12
        or abs(kv[a] - kv[b]) > 1e-9 * max(kv[a], kv[b])
    )
    if not is_xf:
        r = max(r, 1e-7)
        return (
            f"New Line.{name} bus1={_dss_name(a)} bus2={_dss_name(b)} phases=3 "
            f"r1={r:.9g} x1={x:.9g} r0={r:.9g} x0={x:.9g} c1=0 c0=0 "
            "length=1 units=none"
        )
    mva = max(
        float(_sched(line.get("tmax_ab"), block) or 0.0),
        d.line_capacity.get(str(line["name"]), 0.0),
        1.0,
    )
    zb = kv[b] * kv[b] / mva
    rpct = max(r / zb * 100.0, 1e-7)
    xpct = max(x / zb * 100.0, 1e-7)
    return (
        f"New Transformer.{name} phases=3 windings=2 "
        f"buses=[{_dss_name(a)} {_dss_name(b)}] conns=[wye wye] "
        f"kVs=[{kv[a]:.9g} {kv[b]:.9g}] kVAs=[{mva * 1000:.9g} {mva * 1000:.9g}] "
        f"%Rs=[{rpct / 2:.9g} {rpct / 2:.9g}] XHL={xpct:.9g} %noloadloss=0 %imag=0 "
        f"taps=[1 {1.0 / tap:.9g}] MinTap=0.5 MaxTap=1.5"
    )


def _unbuilt(line: dict[str, Any], d: Dispatch) -> bool:
    """A zero-capacity candidate line with no built capacity."""
    cap = line.get("capacity")
    if not isinstance(cap, (int, float)) or cap > 0 or "expcap" not in line:
        return False
    return d.line_capacity.get(str(line["name"]), 0.0) <= 1e-9


def read_dispatch(
    planning: dict[str, Any], results_dir: str | Path, block: int
) -> Dispatch:
    """Read the solved values of flat block *block* from a gtopt output dir."""
    from gtopt_shared.case_reader import TimeGrid  # noqa: PLC0415
    from gtopt_shared.results_reader import GtoptResults  # noqa: PLC0415

    grid = TimeGrid.from_planning(planning)
    res = GtoptResults(results_dir, grid)
    system = planning["system"]
    d = Dispatch()

    def pick(
        cls: str, fld: str, elems: list[dict[str, Any]], into: dict[str, float]
    ) -> None:
        if not res.has(cls, fld):
            return
        for e in elems:
            into[str(e["name"])] = float(res.block_of(cls, fld, e.get("uid"))[0, block])

    demands = system.get("demand_array", [])
    gens = system.get("generator_array", [])
    pick("Demand", "load_sol", demands, d.load)
    pick("Generator", "generation_sol", gens, d.gen)
    pick("Generator", "qgen_sol", gens, d.qgen)
    lines = system.get("line_array", [])
    if res.has("Line", "vsqtap_sol") and res.has("Bus", "vsq_sol"):
        # optimised taps: y = w_a/t² (Line.vsqtap) and w_a (Bus.vsq)
        bus_uid = {str(b["name"]): b["uid"] for b in system.get("bus_array", [])}
        for e in lines:
            if "tap_ratio_min" not in e and "tap_ratio_max" not in e:
                continue
            ba = e["bus_a"]
            ua = bus_uid.get(str(ba), ba if isinstance(ba, int) else None)
            y = float(res.block_of("Line", "vsqtap_sol", e.get("uid"))[0, block])
            wa = float(res.block_of("Bus", "vsq_sol", ua)[0, block])
            if y > 0.0 and wa > 0.0:
                d.tap[str(e["name"])] = math.sqrt(wa / y)
    for e in lines:
        if res.has("Line", "capainst_sol"):
            v = res.stage_of("Line", "capainst_sol", e.get("uid"))[0, 0]
            if v > 0:
                d.line_capacity[str(e["name"])] = float(v)
    for dem in demands:
        name = str(dem["name"])
        if name in d.load:
            d.qload[name] = d.load[name] * tan_phi(dem.get("power_factor"))
    bats = system.get("battery_array", [])
    if bats and res.has("Battery", "finp_sol"):
        dis: dict[str, float] = {}
        chg: dict[str, float] = {}
        pick("Battery", "fout_sol", bats, dis)
        pick("Battery", "finp_sol", bats, chg)
        for name in dis.keys() | chg.keys():
            d.battery[name] = dis.get(name, 0.0) - chg.get(name, 0.0)
    return d
