"""gtopt solves of the native gas elements vs the prototype.

Needs a gtopt binary with the gas elements: set ``GTOPT_BIN`` (CTest
does).  Three groups:

* tiny + literature cases vs the prototype's independent scipy-LP
  expected values (objective 1e-5 relative, pressures 0.01 bar);
* the central-Chile plant case (Renca minimum-pressure sensitivities x
  Quillota compressor x booster x derate): native vs the prototype's
  generic DecisionVariable/UserConstraint form (``--legacy``) solved by
  the same gtopt -- objective, pressures, gas prices, plant output;
* multi-day line pack (1 and 3 days) on the central-Chile network
  (both central-Chile networks live in the external case repository,
  ``$GTOPT_CASES_DIR/chile/gas_network/central_chile_renca/gasnet/``;
  the tests skip without it);
* benchmark cases under ``cases/gas_*`` (GasModels case-6, Hu & Ryan
  6b7n / 24b20n, Ratha 24el-12ng) vs their scipy references, radial
  tangent form and linearized pipes + gas SLP;
* the Peru / Camisea study scenarios (base, dry, price0; the 13-day
  KP-43 rupture as a ``slow`` test) vs the prototype's reference-LP
  objectives
  (``$GTOPT_CASES_DIR/peru/gas_network/camisea/gasnet/
  study_scenarios.json.xz``, generated by the prototype's own scenario
  builders on study/pcp-loss-eval 5ade1771d; the tests skip without it).
"""

