pytestmark = pytest.mark.integration

GTOPT_BIN = os.environ.get("GTOPT_BIN", "")
needs_gtopt = pytest.mark.skipif(
    not GTOPT_BIN or not Path(GTOPT_BIN).is_file(),
    reason="set GTOPT_BIN to a gtopt build with the gas elements",
)

#: Renca minimum fuel-gas pressure sensitivities [bar abs].
RENCA_PMIN = (21.7, 22.7, 26.0, 31.0)


class Run:
    """One solved planning: CSV outputs keyed by element name."""

    def __init__(self, planning: dict[str, Any], workdir: Path) -> None:
        workdir.mkdir(parents=True, exist_ok=True)
        (workdir / "planning.json").write_text(json.dumps(planning), encoding="utf-8")
        proc = subprocess.run(
            ["bash", "-c", f'ulimit -c unlimited; exec "{GTOPT_BIN}" planning.json'],
            cwd=workdir,
            capture_output=True,
            text=True,
            timeout=1500,
            check=False,
        )
        assert proc.returncode == 0, proc.stderr[-2000:]
        self.out = workdir / "output"
        self.system = planning["system"]
        with (self.out / "solution.csv").open(encoding="utf-8") as fh:
            row = next(csv.DictReader(fh))
        assert row["status_name"] == "optimal", row
        self.obj = float(row["obj_value"])

    def table(self, cls: str, attr: str, array: str) -> dict[str, list[float]]:
        """``{element name: per-block values}`` of ``<cls>/<attr>.csv``."""
        names = {e["uid"]: e["name"] for e in self.system.get(array, [])}
        paths = sorted((self.out / cls).glob(f"{attr}_s*_p*.csv")) or [
            self.out / cls / f"{attr}.csv"
        ]
        rows: list[dict[str, str]] = []
        for path in paths:
            with path.open(encoding="utf-8") as fh:
                rows += list(csv.DictReader(fh))
        out: dict[str, list[float]] = {}
        if "value" in rows[0]:  # long layout: scenario,stage,block,uid,value
            rows.sort(
                key=lambda r: (int(r["scenario"]), int(r["stage"]), int(r["block"]))
            )
            for r in rows:
                uid = int(r["uid"])
                out.setdefault(names.get(uid, str(uid)), []).append(float(r["value"]))
            return out
        for key in rows[0]:  # wide layout: one uid:<n> column per element
            if key.startswith("uid:"):
                uid = int(key.split(":", 1)[1])
                out[names.get(uid, str(uid))] = [float(r[key]) for r in rows]
        return out

    # native readers --------------------------------------------------------
    def pressure(self) -> dict[str, list[float]]:
        return self.table("GasNode", "pressure_sol", "gas_node_array")

    def price(self) -> dict[str, list[float]]:
        return self.table("GasNode", "balance_dual", "gas_node_array")

    def generation(self) -> dict[str, list[float]]:
        return self.table("Generator", "generation_sol", "generator_array")

    # legacy readers --------------------------------------------------------
    def dv(self) -> dict[str, list[float]]:
        return self.table("DecisionVariable", "value_sol", "decision_variable_array")

    def uc_dual(self) -> dict[str, list[float]]:
        return self.table("UserConstraint", "constraint_dual", "user_constraint_array")


def _close(got: list[float], exp: list[float], tol: float) -> bool:
    return len(got) == len(exp) and all(abs(a - b) <= tol for a, b in zip(got, exp))


@needs_gtopt
@pytest.mark.parametrize("name", sorted(VARIANTS))
def test_tiny_native_vs_expected(
    name: str, tiny_expected: dict[str, Any], tmp_path: Path
) -> None:
    case, _, _, node, gen = VARIANTS[name]
    run = Run(build_native(load_case(case), variant_options(name))[0], tmp_path)
    exp = tiny_expected[name]
    assert run.obj == pytest.approx(exp["objective"], rel=1e-5)
    press = run.pressure()
    for n, ps in exp["pressure"].items():
        if name == "lp_pack":  # block 4: only pi_S + pi_T is pinned
            assert _close(press[n][:3], ps[:3], 0.01), (n, press[n], ps)
        else:
            assert _close(press[n], ps, 0.01), (n, press[n], ps)
    assert _close(run.generation()[gen], exp["generation"], 0.01)
    assert _close(run.price()[node], exp["gas_price"], 0.01)


@needs_gtopt
@pytest.mark.parametrize("name", sorted(LIT_CASES))
def test_literature_native_vs_expected(
    name: str, lit_expected: dict[str, Any], tmp_path: Path
) -> None:
    run = Run(build_native(load_lit(name), lit_options())[0], tmp_path)
    exp = lit_expected[name]
    assert run.obj == pytest.approx(exp["objective"], rel=1e-5)
    press = run.pressure()
    for n, p in exp["pressure"].items():
        assert press[n][0] == pytest.approx(p, abs=0.01), n


#: External case-repository folders of the central-Chile and Peru networks.
CENTRAL_CHILE_DIR = "chile/gas_network/central_chile_renca/gasnet"
CAMISEA_DIR = "peru/gas_network/camisea/gasnet"


def _external(relpath: str) -> Path:
    """``$GTOPT_CASES_DIR/<relpath>``; skips the test when it is missing."""
    path = external_case_path(relpath)
    if path is None:
        pytest.skip(missing_case_reason(relpath))
    return path


def _central_chile(plants: bool) -> dict[str, Any]:
    name = "central_chile_plants" if plants else "central_chile"
    path = _external(f"{CENTRAL_CHILE_DIR}/{name}.gasnet.json")
    return json.loads(path.read_text(encoding="utf-8"))


def _compare(
    desc: dict[str, Any],
    opts: BuildOptions,
    tmp_path: Path,
    pressures: bool = True,
) -> None:
    """Native vs legacy: objective, pressures, gas prices, plant output.

    ``pressures=False`` for multi-day line pack: storage makes the
    pressure trajectory degenerate (equal-cost profiles), so only the
    priced quantities are compared there.
    """
    nat = Run(build_native(desc, opts)[0], tmp_path / "native")
    leg_planning, _ = build_legacy(desc, opts)
    leg = Run(leg_planning, tmp_path / "legacy")
    assert nat.obj == pytest.approx(leg.obj, rel=1e-5)
    dv = leg.dv()
    duals = leg.uc_dual()
    for node, ps in nat.pressure().items() if pressures else ():
        exp = [math.sqrt(max(x, 0.0)) for x in dv[f"pi_{node}"]]
        assert _close(ps, exp, 0.01), (node, ps, exp)
    for node, prices in nat.price().items():
        exp = duals[f"gas_balance_{node}"]
        assert _close(prices, exp, 0.01 * max(1.0, *map(abs, exp))), node
    gen_n, gen_l = nat.generation(), leg.generation()
    for g, vals in gen_n.items():
        assert _close(vals, gen_l[g], 0.01), g


@needs_gtopt
@pytest.mark.parametrize("pmin", RENCA_PMIN)
@pytest.mark.parametrize("compressor", ["series", "off"])
@pytest.mark.parametrize("booster", ["off", "on"])
def test_central_chile_renca(
    pmin: float, compressor: str, booster: str, tmp_path: Path
) -> None:
    opts = BuildOptions(
        compressor=compressor, plant_pmin={"NUEVA_RENCA": pmin}, booster=booster
    )
    _compare(_central_chile(plants=True), opts, tmp_path)


@needs_gtopt
@pytest.mark.parametrize("booster", ["off", "on"])
def test_central_chile_renca_derate(booster: str, tmp_path: Path) -> None:
    opts = BuildOptions(
        compressor="series",
        plant_pmin={"NUEVA_RENCA": 22.7},
        booster=booster,
        derate=True,
    )
    _compare(_central_chile(plants=True), opts, tmp_path)


@needs_gtopt
@pytest.mark.parametrize("days", [1, 3])
@pytest.mark.parametrize("compressor", ["off", "series"])
def test_multi_day_linepack(days: int, compressor: str, tmp_path: Path) -> None:
    opts = BuildOptions(
        compressor=compressor,
        fuel_model="saldarriaga" if compressor == "series" else None,
        linepack=True,
        nblocks=24 * days,
    )
    _compare(_central_chile(plants=False), opts, tmp_path, pressures=days == 1)


#: Repository ``cases/`` directory (benchmark cases with expected.json).
REPO_CASES = Path(__file__).resolve().parents[3] / "cases"


def _expected_objective(case: str, variant: str) -> float:
    exp = json.loads((REPO_CASES / case / "expected.json").read_text(encoding="utf-8"))
    if case == "gas_case6":
        if variant == "gas_case6_meshed":
            return exp["welfare_offset"] + exp["exact"]["objective"]
        return float(exp["tangent_lp"]["gtopt_objective"])
    if case == "gas_ratha_24el_12ng":
        return float(exp["objective_slp"])
    if variant.endswith("_slp"):
        return float(exp["objective_exact"])
    return float(exp["objective_tangent_lp"])


#: (case directory, planning JSON stem): radial tangent and linearized + SLP.
BENCHMARKS = (
    ("gas_case6", "gas_case6"),
    ("gas_case6", "gas_case6_meshed"),
    ("gas_hu_ryan_6b7n", "gas_hu_ryan_6b7n"),
    ("gas_hu_ryan_24b20n", "gas_hu_ryan_24b20n"),
    ("gas_hu_ryan_24b20n", "gas_hu_ryan_24b20n_slp"),
    ("gas_ratha_24el_12ng", "gas_ratha_24el_12ng"),
)


@needs_gtopt
@pytest.mark.parametrize(
    ("case", "variant"), BENCHMARKS, ids=[b[1] for b in BENCHMARKS]
)
def test_benchmark_objective(case: str, variant: str, tmp_path: Path) -> None:
    folder = "gas_case6_meshed" if variant == "gas_case6_meshed" else case
    planning = json.loads(
        (REPO_CASES / folder / f"{variant}.json").read_text(encoding="utf-8")
    )
    run = Run(planning, tmp_path)
    assert run.obj == pytest.approx(_expected_objective(case, variant), rel=1e-5)


def _study(case: str, name: str) -> dict[str, Any]:
    path = _external(f"{CAMISEA_DIR}/study_scenarios.json.xz")
    data = json.loads(lzma.decompress(path.read_bytes()))
    return data[case][name]


def _study_objective(case: str, name: str, lp: str, tmp_path: Path) -> None:
    sc = _study(case, name)
    opts = BuildOptions(
        compressor=sc["compressor"], linepack=lp == "on", nblocks=sc["nblocks"]
    )
    run = Run(build_native(sc["description"], opts)[0], tmp_path)
    assert run.obj == pytest.approx(sc["objective"][lp], rel=1e-5)


