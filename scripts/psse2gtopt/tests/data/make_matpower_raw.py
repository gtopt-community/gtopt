"""Regenerate ``ieee14.raw`` / ``ieee39.raw`` from the MATPOWER cases.

Provenance
----------
The two PSS/E RAW fixtures in this directory are *generated* by this
script; they are not copied from any other PSS/E file.  The network
data comes from the MATPOWER ``case14`` (IEEE 14-bus) and ``case39``
(New England 39-bus) cases as shipped by pandapower
(``pandapower.networks.case14()`` / ``case39()``, BSD-3-Clause, data
converted from MATPOWER).  The underlying case data are public IEEE
benchmark systems: IEEE 14-bus from the University of Washington Power
Systems Test Case Archive, and the New England 39-bus system from
Athay, Podmore and Virmani (1979) / Pai (1989).  MATPOWER is by
R. D. Zimmerman, C. E. Murillo-Sanchez et al.

pandapower converts the cases to its internal tables; ``to_ppc`` turns
them back into MATPOWER-style per-unit arrays (bus / gen / branch on a
100 MVA base), which this script writes out as PSS/E RAW:

* ``ieee14.raw`` as revision 32 (9-field bus records), and
* ``ieee39.raw`` as revision 33 (13-field bus records),

so the fixtures keep covering both RAW revisions the parser supports.
Lines become BRANCH records; pandapower transformers become two-winding
TRANSFORMER records (CW=1, CZ=1, WINDV1 = MATPOWER tap ratio).  A
MATPOWER ``rateA`` of 0 (unlimited) is written as RATEA = 0, MBASE is
the 100 MVA system base, and bus base kV are pandapower's values
(MATPOWER ``case14`` itself leaves them at 0).

Usage (from ``scripts/``)::

    python psse2gtopt/tests/data/make_matpower_raw.py

The output is deterministic for a given pandapower version.
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

_OUT_DIR = Path(__file__).resolve().parent

# pandapower's to_ppc stores MATPOWER's "rateA = 0 (unlimited)" as
# ~9900 MVA; map it back to 0 when writing the RAW file.
_UNLIMITED_MVA = 9000.0


def _ppc_for(case_fn):
    """Return ``(ppc, net)`` for a pandapower MATPOWER case."""
    # pylint: disable=import-outside-toplevel
    from pandapower.converter.matpower import to_ppc

    net = case_fn()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        ppc = to_ppc(net, init="flat", calculate_voltage_angles=False)
    return ppc, net


def _bus_numbers(ppc, net) -> list[int]:
    """Original (MATPOWER) bus number of each ppc bus row."""
    lookup = net._pd2ppc_lookups["bus"]  # pylint: disable=protected-access
    numbers = [0] * ppc["bus"].shape[0]
    for idx, name in zip(net.bus.index, net.bus.name):
        numbers[int(lookup[idx])] = int(name)
    return numbers


def _fmt(x: float, width: int = 10, prec: int = 3) -> str:
    return f"{x + 0.0:{width}.{prec}f}"


def _rate(x: float) -> float:
    return 0.0 if x >= _UNLIMITED_MVA else round(float(x), 2)


def write_raw(case_fn, path: Path, rev: int, title: str) -> None:
    """Write *case_fn*'s network as PSS/E RAW revision *rev* to *path*."""
    ppc, net = _ppc_for(case_fn)
    base = float(ppc["baseMVA"])
    bus = ppc["bus"]
    gen = ppc["gen"]
    branch = ppc["branch"]
    num = _bus_numbers(ppc, net)

    out: list[str] = [
        f"0, {base:8.2f}, {rev}, 0, 1, 60.00     / PSS(R)E-{rev} RAW "
        "generated by make_matpower_raw.py",
        title,
        "generated from MATPOWER data via pandapower; see make_matpower_raw.py",
    ]

    # --- BUS: I, NAME, BASKV, IDE, AREA, ZONE, OWNER, VM, VA [, NVHI..]
    for i, row in enumerate(bus):
        n = num[i]
        rec = (
            f"{n:6d},'BUS{n:<9d}',{row[9]:9.4f},{int(row[1])},"
            f"   1,   1,   1,{row[7]:7.5f},{row[8]:9.4f}"
        )
        if rev >= 33:
            rec += f",{row[11]:.2f},{row[12]:.2f},{row[11]:.5f},{row[12]:.5f}"
        out.append(rec)
    out.append("0 / END OF BUS DATA, BEGIN LOAD DATA")

    # --- LOAD: one per bus with nonzero Pd or Qd.
    for i, row in enumerate(bus):
        if row[2] == 0.0 and row[3] == 0.0:
            continue
        rec = (
            f"{num[i]:6d},'1 ',1,   1,   1,{_fmt(row[2])},{_fmt(row[3])},"
            "     0.000,     0.000,     0.000,     0.000,   1,1"
        )
        if rev >= 33:
            rec += ",0"
        out.append(rec)
    out.append("0 / END OF LOAD DATA, BEGIN FIXED SHUNT DATA")

    # --- FIXED SHUNT: I, ID, STATUS, GL, BL
    for i, row in enumerate(bus):
        if row[4] != 0.0 or row[5] != 0.0:
            out.append(f"{num[i]:6d},'1 ',1,{_fmt(row[4])},{_fmt(row[5])}")
    out.append("0 / END OF FIXED SHUNT DATA, BEGIN GENERATOR DATA")

    # --- GENERATOR: I,ID,PG,QG,QT,QB,VS,IREG,MBASE,ZR,ZX,RT,XT,GTAP,STAT,
    #                RMPCT,PT,PB,O1,F1
    for row in gen:
        out.append(
            f"{num[int(row[0])]:6d},'1 ',{_fmt(row[1])},{_fmt(row[2])},"
            f"{_fmt(row[3])},{_fmt(row[4])},{row[5]:7.5f},     0,"
            f"{_fmt(base)}, 0.00000E+0, 1.00000E+0, 0.00000E+0, "
            f"0.00000E+0,1.00000,{int(row[7])},  100.0,"
            f"{_fmt(row[8])},{_fmt(row[9])},   1,1.0000"
        )
    out.append("0 / END OF GENERATOR DATA, BEGIN BRANCH DATA")

    lookups = net._pd2ppc_lookups["branch"]  # pylint: disable=protected-access
    trafo_rows: set[int] = set()
    if "trafo" in lookups:
        start, stop = lookups["trafo"]
        trafo_rows = set(range(start, stop))

    # --- BRANCH: I,J,CKT,R,X,B,RATEA,RATEB,RATEC,GI,BI,GJ,BJ,ST,MET,LEN,O1,F1
    for k, row in enumerate(branch):
        if k in trafo_rows:
            continue
        rate = _rate(row[5])
        out.append(
            f"{num[int(row[0].real)]:6d},{num[int(row[1].real)]:7d},'1 ',"
            f"{row[2].real:11.5E},{row[3].real:11.5E},{row[4].real:10.5f},"
            f"{rate:8.2f},{rate:8.2f},{rate:8.2f},"
            "  0.00000,  0.00000,  0.00000,  0.00000,"
            f"{int(row[10].real)},1,   0.00,   1,1.0000"
        )
    out.append("0 / END OF BRANCH DATA, BEGIN TRANSFORMER DATA")

    # --- TRANSFORMER (two-winding, 4 lines each)
    for k in sorted(trafo_rows):
        row = branch[k]
        rate = _rate(row[5].real)
        ratio = row[8].real if row[8].real != 0.0 else 1.0
        out.extend(
            [
                f"{num[int(row[0].real)]:6d},{num[int(row[1].real)]:7d},"
                "     0,'1 ',1,1,1, 0.00000E+0, 0.00000E+0,2,"
                f"'            ',{int(row[10].real)},   1,1.0000",
                f"{row[2].real:11.5E},{row[3].real:11.5E},{base:9.2f}",
                f"{ratio:7.5f},   0.000,{row[9].real:8.3f},{rate:8.2f},"
                f"{rate:8.2f},{rate:8.2f},0,      0, 1.10000, 0.90000, "
                "1.10000, 0.90000,  33, 0, 0.00000, 0.00000,  0.000",
                "1.00000,   0.000",
            ]
        )
    out.append("0 / END OF TRANSFORMER DATA, BEGIN AREA DATA")
    out.append("0 / END OF AREA DATA")
    out.append("Q")
    path.write_text("\n".join(out) + "\n", encoding="latin-1")


def main() -> int:
    """Regenerate both fixtures next to this script."""
    # pylint: disable=import-outside-toplevel
    import pandapower.networks as pn

    write_raw(pn.case14, _OUT_DIR / "ieee14.raw", 32, "IEEE 14 BUS TEST CASE")
    write_raw(pn.case39, _OUT_DIR / "ieee39.raw", 33, "NEW ENGLAND 39 BUS TEST CASE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
